# Address class
class Address:

    #constructor
    def __init__(self, city, state, pincode):
        # store city, state, pincode
        self.city = city
        self.state = state
        self.pincode = pincode

# create address object 
address1 = Address("Pune", "Maharashtra", 411001)

# Print address details
print(address1.city)
print(address1.state)
print(address1.pincode)
